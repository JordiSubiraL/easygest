CREATE TABLE public.country (
	id int8 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	code varchar(255) NOT NULL UNIQUE,
	description varchar(255) NOT NULL,
	prefix varchar(10) NULL,
	create_date timestamp(6) NOT NULL,
	create_user varchar(255) NOT NULL,
	modify_date timestamp(6) NULL,
	modify_user varchar(255) NULL,
	version bigint NOT NULL DEFAULT 0,
	CONSTRAINT country_pkey PRIMARY KEY (id)
);

COMMENT ON TABLE country is 'Table containing countries';
COMMENT ON COLUMN country.id is 'Unique country identifier';
COMMENT ON COLUMN country.code is 'Unique code identifying the country';
COMMENT ON COLUMN country.description is 'Country description';
COMMENT ON COLUMN country.prefix is 'Country phone prefix';
COMMENT ON COLUMN country.create_date is 'Audit field that stores record creation date';
COMMENT ON COLUMN country.create_user is 'Audit field saved by the record creation user';
COMMENT ON COLUMN country.modify_date is 'Audit field that stores the date the record was modified';
COMMENT ON COLUMN country.modify_user is 'Audit field held by the user of the last record modification';
COMMENT ON COLUMN country.version is 'Version field for optimistic locking';

